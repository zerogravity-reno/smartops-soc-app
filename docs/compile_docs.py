#!/usr/bin/env python3
"""Compiles every docs/sessions/*.md file into a single docs/PROJECT_DOCS.md.

Each session file starts with a small frontmatter block:

    ---
    date: 2026-08-05
    title: Subtask contract, EDR diagram, backend scaffolding
    ---

Run after each work session:

    python docs/compile_docs.py

No third-party dependencies on purpose -- this should run with whatever
Python happens to be on hand, independent of the uv workspace.
"""

from __future__ import annotations

import re
from pathlib import Path

DOCS_DIR = Path(__file__).parent
SESSIONS_DIR = DOCS_DIR / "sessions"
OUTPUT = DOCS_DIR / "PROJECT_DOCS.md"

FRONTMATTER_RE = re.compile(r"^---\s*\n(.*?)\n---\s*\n(.*)$", re.DOTALL)


def parse_session(path: Path) -> tuple[dict[str, str], str]:
    text = path.read_text(encoding="utf-8")
    match = FRONTMATTER_RE.match(text)
    if not match:
        raise ValueError(f"{path} is missing a leading --- frontmatter block")
    raw_meta, body = match.groups()
    meta = {}
    for line in raw_meta.splitlines():
        if not line.strip():
            continue
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip()
    if "date" not in meta or "title" not in meta:
        raise ValueError(f"{path} frontmatter must set both `date` and `title`")
    return meta, body.strip()


def anchor_for(meta: dict[str, str], path: Path) -> str:
    slug = meta.get("title", path.stem).lower().replace(" ", "-")
    return re.sub(r"[^a-z0-9\-]", "", slug)


def main() -> None:
    session_files = sorted(SESSIONS_DIR.glob("*.md"))
    if not session_files:
        raise SystemExit(f"No session files found in {SESSIONS_DIR}")

    entries = [(path, *parse_session(path)) for path in session_files]

    lines = [
        "# SmartOps SOC App — Project Documentation",
        "",
        "_Compiled from `docs/sessions/`. Do not edit this file directly --",
        "edit the session file and re-run `python docs/compile_docs.py`._",
        "",
        "## Sessions",
        "",
    ]
    for path, meta, _ in entries:
        anchor = anchor_for(meta, path)
        lines.append(f"- [{meta['date']} — {meta['title']}](#{anchor})")

    for path, meta, body in entries:
        anchor = anchor_for(meta, path)
        lines.append("")
        lines.append("---")
        lines.append("")
        lines.append(f'<a id="{anchor}"></a>')
        lines.append(f"## {meta['date']} — {meta['title']}")
        lines.append("")
        lines.append(body)

    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Compiled {len(entries)} session doc(s) -> {OUTPUT}")


if __name__ == "__main__":
    main()
